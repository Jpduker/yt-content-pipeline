"""Build library/music/catalog.json + CATALOG.md from every audio file under library/music/ (needs librosa: lemo venv)."""
import sys, os, json, glob
import numpy as np, librosa
ROOT = sys.argv[1]; NAMES = 'C C# D D# E F F# G G# A A# B'.split()
MAJ = np.array([6.35, 2.23, 3.48, 2.33, 4.38, 4.09, 2.52, 5.19, 2.39, 3.66, 2.29, 2.88]); MIN = np.array([6.33, 2.68, 3.52, 5.38, 2.6, 3.53, 2.54, 4.75, 3.98, 2.69, 3.34, 3.17])
out = []
for f in sorted(glob.glob(os.path.join(ROOT, '**', '*.*'), recursive=True)):
    if not f.lower().endswith(('.mp3', '.wav', '.m4a', '.ogg', '.flac')): continue
    rel = os.path.relpath(f, ROOT); parts = rel.split(os.sep)
    y, sr = librosa.load(f, sr=22050, mono=True)
    tempo = float(np.atleast_1d(librosa.beat.beat_track(y=y, sr=sr)[0])[0]); ch = librosa.feature.chroma_cqt(y=y, sr=sr).mean(1)
    key = max([(np.corrcoef(np.roll(MAJ, k), ch)[0, 1], NAMES[k] + ' major') for k in range(12)] + [(np.corrcoef(np.roll(MIN, k), ch)[0, 1], NAMES[k] + ' minor') for k in range(12)])[1]
    rms = librosa.feature.rms(y=y)[0]; tt = librosa.times_like(rms, sr=sr); dur = len(y) / sr
    curve = [round(float(20 * np.log10(rms[(tt >= i) & (tt < i + 5)].mean() + 1e-9)), 1) for i in range(0, int(dur), 5)]
    side = f + '.json'; meta = json.load(open(side)) if os.path.exists(side) else {}
    out.append({'file': rel, 'source': parts[0], 'mood': parts[1] if len(parts) > 2 else None, 'seconds': round(dur, 1), 'bpm': round(tempo), 'key': key,
                'energy_db_per_5s': curve, 'publishable': parts[0] != 'local-test-only', **meta})
    print(rel, round(dur), 's', round(tempo), 'bpm', key)
json.dump(out, open(os.path.join(ROOT, 'catalog.json'), 'w'), indent=1)
with open(os.path.join(ROOT, 'CATALOG.md'), 'w') as m:
    m.write('# Music catalog (generated by pipeline/music-catalog.sh, do not edit)\n\n| File | Mood | Length | BPM | Key | Publishable | Attribution |\n|---|---|---|---|---|---|---|\n')
    for r in out: m.write(f"| {r['file']} | {r['mood'] or ''} | {r['seconds']} s | {r['bpm']} | {r['key']} | {'yes' if r['publishable'] else '**LOCAL TEST ONLY**'} | {r.get('attribution') or ''} |\n")
print(len(out), 'tracks ->', os.path.join(ROOT, 'catalog.json'))
